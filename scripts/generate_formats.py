#!/usr/bin/env python3
"""Regenerate the bundled catalog from the installed FFprobe build."""
import concurrent.futures
import json
from pathlib import Path
import re
import subprocess

def run(*args):
    return subprocess.check_output(["ffprobe", "-hide_banner", *args], stderr=subprocess.STDOUT, text=True)

version = run("-version").splitlines()[0]
names = sorted(set(re.findall(r"^ D\s+(\S+)", run("-demuxers"), re.M)))

def describe(name):
    detail = run("-h", "demuxer=" + name.split(",")[0])
    match = re.search(r"Common extensions: (.+)\.", detail)
    return {"names": name.split(","), "extensions": match.group(1).split(",") if match else []}

with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
    catalog = list(pool.map(describe, names))
text = '// Code generated by scripts/generate_formats.py; DO NOT EDIT.\npackage media\n\n'
text += 'const FormatCatalogSource = ' + json.dumps(version) + '\n'
text += 'const FormatCatalogJSON = `' + json.dumps(catalog, indent=2) + '`\n'
Path(__file__).resolve().parents[1].joinpath("internal/media/formats_generated.go").write_text(text)
print(f"Generated {len(catalog)} demuxers from {version}")
